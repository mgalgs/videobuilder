_BY_ID = {e['id']: e for e in CATALOG}


def get(id):
    return _BY_ID[id]


def ids():
    return tuple(e['id'] for e in CATALOG)


def categories():
    seen = []
    for e in CATALOG:
        if e['category'] not in seen:
            seen.append(e['category'])
    return tuple(seen)


# ---- the builder-facing sheet (skill/make-a-video/reference/capabilities.md) ----

SHEET_PATH = os.path.join('skill', 'make-a-video', 'reference', 'capabilities.md')
_REGEN_CMD = 'python -m videobuilder capabilities sheet > ' + SHEET_PATH


def sheet_markdown():
    """The builder-facing reference generated from CATALOG. Regenerate with
    `_REGEN_CMD`; tests/test_capabilities.py fails if the committed file drifts
    from this."""
    lines = [
        '<!-- GENERATED from videobuilder/capabilities.py by `sheet_markdown()`. Do not hand-edit;',
        f'     regenerate with `{_REGEN_CMD}` after changing the catalog. -->',
        '# Capabilities catalog',
        '',
        'What videobuilder can already do, with a worked example for each. Reach for one of these '
        'before inventing an effect. Adding a capability later means adding one entry to `CATALOG` in '
        '`videobuilder/capabilities.py` and one demo film beside the others in `examples/capabilities/`; '
        'this file and the `/capabilities` page are both generated from that single catalog.',
        '',
    ]
    for category in categories():
        lines.append(f'## {category}')
        lines.append('')
        for e in CATALOG:
            if e['category'] != category:
                continue
            lines.append(f"### {e['title']}")
            lines.append('')
            lines.append(f"**What it looks like:** {e['card']} {e['description']}")
            lines.append('')
            lines.append('**When to use it:** reach for this when a director says something like:')
            for p in e['prompts']:
                lines.append(f'- "{p}"')
            lines.append('')
            lines.append('**How to build it:**')
            for api in e['apis']:
                lines.append(f'- `{api}`')
            lines.append(f"- Read `{e['doc']}`.")
            lines.append('')
            lines.append(f"**Worked example:** `{e['demo']}` — read it before writing something similar from scratch.")
            lines.append('')
    return '\n'.join(lines) + '\n'


# ---- building the clips and posters ----

def _save_poster(cv, path, quality=82):
    from PIL import Image
    cv.surface.flush()
    w, h = cv.surface.get_width(), cv.surface.get_height()
    im = Image.frombuffer('RGBA', (w, h), bytes(cv.surface.get_data()), 'raw', 'BGRA', cv.surface.get_stride(), 1)
    im.convert('RGB').save(path, 'JPEG', quality=quality)


def build(out_dir, only=None, jobs=None, crf=30, log=None):
    """Render every catalog demo (or just the ids in `only`) to `<out_dir>/<id>.mp4`
    (H.264, yuv420p, faststart, audio only where the demo has it) and
    `<out_dir>/<id>.jpg` (a poster from the demo's middle frame — every demo is
    built to be mid-clip-settled by its own enter/hold/exit or periodic-phase
    convention, see examples/capabilities/STYLE.md). Returns a list of
    {id, seconds, bytes} for the ones built, in catalog order."""
    import sys as _sys
    import time as _time
    from . import film as _film
    from .render import render as _render
    log = log or _sys.stderr
    if only is not None:
        unknown = set(only) - set(ids())
        if unknown:
            raise ValueError(f'unknown capability id(s): {", ".join(sorted(unknown))}')
    entries = [e for e in CATALOG if only is None or e['id'] in only]
    os.makedirs(out_dir, exist_ok=True)
    results = []
    for entry in entries:
        path = os.path.join(REPO_ROOT, entry['demo'])
        film = _film.load(path)
        fmt = film.formats[0]
        out_mp4 = os.path.join(out_dir, entry['id'] + '.mp4')
        t0 = _time.time()
        _render(film, out_mp4, fmt, jobs=jobs, crf=crf, log=log)
        poster_n = entry['poster'] if entry['poster'] is not None else film.frames // 2
        poster_cv = film.frame(poster_n, fmt)
        _save_poster(poster_cv, os.path.join(out_dir, entry['id'] + '.jpg'))
        results.append({'id': entry['id'], 'seconds': _time.time() - t0, 'bytes': os.path.getsize(out_mp4)})
    return results
