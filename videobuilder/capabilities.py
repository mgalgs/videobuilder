"""The capabilities catalog: one entry per thing videobuilder can do, each
with a demo film that proves it. This is the single source for both the
`/capabilities` page (editor.py) and the builder-facing sheet
(skill/make-a-video/reference/capabilities.md, generated by `sheet_markdown`
below and checked for drift by tests/test_capabilities.py). Add a capability
by adding one entry here and one demo film at its `demo` path; nothing else
reads capability text directly.

    python -m videobuilder capabilities build --out DIR [--only ID]
"""
import os

