def entries():
    """Every catalog entry: each top-level one, and right after a family,
    its members. What has a demo, a clip and a poster."""
    out = []
    for e in CATALOG:
        out.append(e)
        out.extend(e.get('children', ()))
    return tuple(out)


def families():
    """The family entries (see _family), in catalog order."""
    return tuple(e for e in CATALOG if e.get('children') is not None)


def member_paths():
    """{family id: the file a community member ships} for every family that
    takes them (see _member): community.MEMBER_PATHS."""
    return {f['id']: f['member']['file'] for f in families() if f.get('member')}


def member_name(entry):
    """The registry name a family member answers to (a look's, a type
    style's), or None for one built by hand (paper collage)."""
    return entry.get('look') or entry.get('style')


def kind_groups(family, members=None):
    """The family's members grouped as the page and the sheet show them:
    [(kind, heading, line, members), ...], one group with no heading
    (kind, heading and line None) for a family with no kinds."""
    members = family['children'] if members is None else members
    if not family.get('kinds'):
        return [(None, None, None, list(members))]
    return [(kind, heading, line, [c for c in members if c.get('kind') == kind])
            for kind, heading, line in family['kinds']]


_BY_ID = {e['id']: e for e in entries()}


def resolve(id):
    """The id an entry goes by now: `id` itself, or the entry an old id
    (ALIASES) was merged into. KeyError for an id that never existed."""
    id = ALIASES.get(id, id)
    if id not in _BY_ID:
        raise KeyError(id)
    return id


def get(id):
    """The entry `id` names, an old id (ALIASES) included."""
    return _BY_ID[resolve(id)]


def ids():
    """Every entry's id, families' members included. No new capability may
    reuse one, nor an old id in ALIASES."""
    return tuple(e['id'] for e in entries())


def categories():
    seen = []
    for e in CATALOG:
        if e['category'] not in seen:
            seen.append(e['category'])
    return tuple(seen)


def loose_categories():
    """The categories a capability that isn't a family member may take:
    every one but a family's own section (Looks holds looks only)."""
    own = {f['category'] for f in families()}
    return tuple(c for c in categories() if c not in own)


